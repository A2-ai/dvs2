test_that("dvs_info() reports a local project as dvs info --json does", {
  repo <- new_dvs_test_repo()
  info <- dvs_info()
  expect_equal(info$backend, "local")
  expect_equal(info$compression, "zstd")
  expect_equal(info$connection, "not_applicable")
  expect_equal(info$on_conflict, "abort")
  expect_equal(info$on_conflict_source, "default")
  expect_equal(normalizePath(info$storage), normalizePath(repo$storage))
  expect_equal(normalizePath(info$project_root), normalizePath(repo$repo))
  expect_null(info$logged_in)
})

test_that("dvs_info() reports not being logged in as an answer", {
  new_dvs_test_repo()
  server_project("http://127.0.0.1:9/")
  withr::local_envvar(XDG_CONFIG_HOME = withr::local_tempdir())
  info <- dvs_info()
  expect_equal(info$backend, "server")
  expect_false(info$logged_in)
  expect_equal(info$connection, "unknown")
  expect_equal(info$access, "not_logged_in")
  expect_identical(info$groups, character(0))
  expect_null(info$compression)
  expect_null(info$ignored_compression)
})

test_that("dvs_info() reports a server that does not answer, and an ignored compression line", {
  new_dvs_test_repo()
  server_project("http://127.0.0.1:9/")
  toml <- readLines("dvs.toml")
  writeLines(c('compression = "none"', toml), "dvs.toml")
  xdg <- withr::local_tempdir()
  dir.create(file.path(xdg, "dvs"))
  writeLines('{"http://127.0.0.1:9/": "tok"}', file.path(xdg, "dvs", "credentials.json"))
  withr::local_envvar(XDG_CONFIG_HOME = xdg)
  info <- dvs_info()
  expect_true(info$logged_in)
  expect_equal(info$connection, "unavailable")
  expect_equal(info$connection_error$code, "server_unavailable")
  expect_null(info$access)
  expect_null(info$groups)
  expect_equal(info$ignored_compression, "none")
})

test_that("dvs_info() raises unreadable credentials as credentials_unreadable", {
  new_dvs_test_repo()
  server_project("http://127.0.0.1:9/")
  xdg <- withr::local_tempdir()
  dir.create(file.path(xdg, "dvs"))
  writeLines("not json", file.path(xdg, "dvs", "credentials.json"))
  withr::local_envvar(XDG_CONFIG_HOME = xdg)
  cnd <- tryCatch(dvs_info(), error = identity)
  expect_s3_class(cnd, "dvs_error")
  expect_equal(cnd$code, "credentials_unreadable")
})
